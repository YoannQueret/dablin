const char* LookupECCCountry(uint8_t ecc, uint8_t country_id) {
	for(const ECCCountryEntry& entry : ecc_countries) {
		if(entry.ecc == ecc && entry.country_id == country_id)
			return entry.country;
	}
	return nullptr;
}
